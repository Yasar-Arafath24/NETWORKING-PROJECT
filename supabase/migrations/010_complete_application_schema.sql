-- Reconcile the complete NetSentry schema in existing Supabase projects.
-- Safe to run when the base tables already exist.

create extension if not exists pgcrypto;

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  name varchar(120) not null,
  email varchar(254) not null unique,
  password_hash varchar(256) not null,
  google_subject varchar(255) unique,
  email_verified boolean not null default true,
  role varchar(20) not null default 'user',
  is_active boolean not null default true,
  avatar_url text,
  timezone varchar(64) not null default 'UTC',
  last_login_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.user_sessions (
  id bigint generated by default as identity primary key,
  token_hash varchar(64) not null unique,
  csrf_token varchar(64) not null,
  user_id bigint not null references public.users(id) on delete cascade,
  ip_address inet,
  user_agent text,
  expires_at timestamptz not null,
  revoked_at timestamptz
);

create table if not exists public.email_verifications (
  id bigint generated by default as identity primary key,
  user_id bigint not null unique references public.users(id) on delete cascade,
  code_hash varchar(64) not null,
  expires_at timestamptz not null,
  attempts integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.organizations (
  id bigint generated by default as identity primary key,
  owner_id bigint not null references public.users(id) on delete restrict,
  name varchar(120) not null,
  slug varchar(120) not null unique,
  plan varchar(30) not null default 'free',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.organization_members (
  organization_id bigint not null references public.organizations(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  role varchar(20) not null default 'member',
  invited_at timestamptz not null default now(),
  joined_at timestamptz,
  primary key (organization_id, user_id)
);

create table if not exists public.subscriptions (
  id bigint generated by default as identity primary key,
  user_id bigint references public.users(id) on delete cascade,
  organization_id bigint references public.organizations(id) on delete cascade,
  provider varchar(30) not null default 'manual',
  provider_customer_id varchar(255),
  provider_subscription_id varchar(255),
  status varchar(30) not null default 'active',
  plan varchar(30) not null default 'free',
  current_period_end timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint subscription_owner_check check ((user_id is not null) <> (organization_id is not null))
);

create table if not exists public.analysis_reports (
  id bigint generated by default as identity primary key,
  owner_id bigint references public.users(id) on delete cascade,
  organization_id bigint references public.organizations(id) on delete cascade,
  filename varchar(512) not null default '',
  total_packets integer not null default 0,
  total_flows integer not null default 0,
  suspicious_flows integer not null default 0,
  report_data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.analysis_history (
  id bigint generated by default as identity primary key,
  report_id bigint unique references public.analysis_reports(id) on delete cascade,
  owner_id bigint not null references public.users(id) on delete cascade,
  filename varchar(512) not null default '',
  total_packets integer not null default 0,
  total_flows integer not null default 0,
  suspicious_flows integer not null default 0,
  analysis_status varchar(32) not null default 'completed',
  created_at timestamptz not null default now()
);

create table if not exists public.traffic_flow_records (
  id bigint generated by default as identity primary key,
  owner_id bigint not null references public.users(id) on delete cascade,
  report_id bigint not null references public.analysis_reports(id) on delete cascade,
  flow_index integer not null default 0,
  src_ip varchar(45),
  dst_ip varchar(45),
  src_port integer,
  dst_port integer,
  protocol varchar(16),
  packet_count integer not null default 0,
  total_bytes bigint not null default 0,
  duration double precision not null default 0,
  anomaly boolean not null default false,
  label varchar(32) not null default 'UNASSESSED',
  anomaly_score double precision,
  flow_data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (report_id, flow_index)
);

create table if not exists public.live_flow_records (
  id bigint generated by default as identity primary key,
  owner_id bigint references public.users(id) on delete cascade,
  session_id varchar(100) not null,
  flow_id integer not null,
  src_ip varchar(45) not null,
  dst_ip varchar(45) not null,
  src_port integer not null,
  dst_port integer not null,
  protocol varchar(16) not null,
  packet_count integer not null default 0,
  total_bytes bigint not null default 0,
  duration double precision not null default 0,
  anomaly boolean not null default false,
  label varchar(32) not null default 'UNASSESSED',
  anomaly_score double precision,
  features jsonb not null default '{}'::jsonb,
  first_seen timestamptz not null default now(),
  last_updated timestamptz not null default now(),
  unique (session_id, flow_id)
);

create table if not exists public.network_alerts (
  id bigint generated by default as identity primary key,
  owner_id bigint references public.users(id) on delete cascade,
  session_id varchar(100) not null,
  flow_id integer not null,
  severity varchar(20) not null default 'MEDIUM',
  title varchar(200) not null,
  description varchar(1000) not null,
  anomaly_score double precision not null,
  flow_data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.monitored_websites (
  id bigint generated by default as identity primary key,
  owner_id bigint not null references public.users(id) on delete cascade,
  organization_id bigint references public.organizations(id) on delete cascade,
  name varchar(120) not null,
  url varchar(2048) not null,
  platform varchar(20) not null default 'custom',
  token_hash varchar(64) not null,
  collector_revoked_at timestamptz,
  enabled boolean not null default true,
  authorization_confirmed boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.website_traffic_events (
  id bigint generated by default as identity primary key,
  site_id bigint not null references public.monitored_websites(id) on delete cascade,
  request_path varchar(512) not null,
  method varchar(12) not null,
  status_code integer not null,
  duration_ms double precision not null default 0,
  response_bytes bigint not null default 0,
  source_ip varchar(64) not null default '',
  user_agent varchar(256) not null default '',
  severity varchar(16) not null default 'INFO',
  reason varchar(500) not null default '',
  event_data jsonb not null default '{}'::jsonb,
  request_timestamp timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.website_security_alerts (
  id bigint generated by default as identity primary key,
  site_id bigint not null references public.monitored_websites(id) on delete cascade,
  category varchar(64) not null,
  title varchar(180) not null,
  severity varchar(16) not null,
  risk_score integer not null default 0,
  source_ip varchar(64) not null default '',
  endpoint varchar(512) not null default '',
  explanation varchar(2000) not null,
  status varchar(20) not null default 'OPEN',
  related_event_count integer not null default 1,
  first_seen timestamptz not null default now(),
  last_seen timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table if not exists public.website_alert_status_changes (
  id bigint generated by default as identity primary key,
  alert_id bigint not null references public.website_security_alerts(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  previous_status varchar(20) not null,
  new_status varchar(20) not null,
  changed_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  user_id bigint references public.users(id) on delete set null,
  organization_id bigint references public.organizations(id) on delete set null,
  action varchar(100) not null,
  resource_type varchar(100),
  resource_id varchar(100),
  metadata jsonb not null default '{}'::jsonb,
  ip_address inet,
  created_at timestamptz not null default now()
);

