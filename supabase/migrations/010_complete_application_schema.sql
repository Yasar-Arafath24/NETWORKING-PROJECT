alter table public.monitored_websites add column if not exists collector_revoked_at timestamptz;
alter table public.website_traffic_events add column if not exists request_timestamp timestamptz;
alter table public.live_flow_records add column if not exists owner_id bigint references public.users(id) on delete cascade;
alter table public.network_alerts add column if not exists owner_id bigint references public.users(id) on delete cascade;

create index if not exists ix_users_email on public.users(email);
create index if not exists ix_user_sessions_user_id on public.user_sessions(user_id);
create index if not exists ix_analysis_reports_owner_created on public.analysis_reports(owner_id, created_at desc);
create index if not exists ix_analysis_history_owner_created on public.analysis_history(owner_id, created_at desc);
create index if not exists ix_traffic_flow_records_report on public.traffic_flow_records(report_id, flow_index);
create index if not exists ix_traffic_flow_records_owner_created on public.traffic_flow_records(owner_id, created_at desc);
create index if not exists ix_live_flow_records_owner_updated on public.live_flow_records(owner_id, last_updated desc);
create index if not exists ix_network_alerts_owner_created on public.network_alerts(owner_id, created_at desc);
create index if not exists ix_monitored_websites_owner_created on public.monitored_websites(owner_id, created_at desc);
create index if not exists ix_website_traffic_events_site_created on public.website_traffic_events(site_id, created_at desc);
create index if not exists ix_website_security_alerts_site_status on public.website_security_alerts(site_id, status, last_seen desc);
create index if not exists ix_audit_logs_created_at on public.audit_logs(created_at desc);

