create table if not exists public.website_security_alerts (
  id bigint generated by default as identity primary key,
  site_id bigint not null references public.monitored_websites(id) on delete cascade,
  category varchar(64) not null,
  title varchar(180) not null,
  severity varchar(16) not null,
  risk_score integer not null default 0,
  source_ip varchar(64) not null default '',
  endpoint varchar(512) not null default '',
  explanation varchar(2000) not null,
  status varchar(20) not null default 'OPEN',
  related_event_count integer not null default 1,
  first_seen timestamptz not null default now(),
  last_seen timestamptz not null default now(),
  created_at timestamptz not null default now()
);
create index if not exists ix_website_security_alerts_site_id
  on public.website_security_alerts(site_id);
create index if not exists ix_website_alert_site_status_last_seen
  on public.website_security_alerts(site_id, status, last_seen);
create index if not exists ix_website_security_alerts_created_at
  on public.website_security_alerts(created_at desc);
alter table public.website_security_alerts enable row level security;
revoke all on table public.website_security_alerts from anon, authenticated;

create table if not exists public.website_alert_status_changes (
  id bigint generated by default as identity primary key,
  alert_id bigint not null references public.website_security_alerts(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  previous_status varchar(20) not null,
  new_status varchar(20) not null,
  changed_at timestamptz not null default now()
);
create index if not exists ix_website_alert_status_changes_alert_id
  on public.website_alert_status_changes(alert_id);
create index if not exists ix_website_alert_status_changes_user_id
  on public.website_alert_status_changes(user_id);
alter table public.website_alert_status_changes enable row level security;
revoke all on table public.website_alert_status_changes from anon, authenticated;
